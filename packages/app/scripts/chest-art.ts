/**
 * The chests' shape (#874): `src/components/elements/chest-art-shapes.ts` is generated from the owner's Font Awesome Pro file
 * (`vendor/fontawesome/solid.min.js`), Font Awesome's `treasure-chest` cut into its parts (the lid's three panels, the body's
 * three, the keyhole) and rounded as the game icons' (`scripts/game-icons.ts`). The chests' simple icons tone those parts; the
 * detailed art is drawn for Paved (`elements/chest-designs.ts`).
 *
 *   node scripts/chest-art.ts            write the shapes file
 *   node scripts/chest-art.ts --check    fail when the committed file differs from what the source gives
 *
 * Node 24 runs it as is (type stripping): the syntax stays erasable. No package.
 * The drawing is Font Awesome's, unchanged; `public/THIRD_PARTY_NOTICES.txt` records the shape as derived.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { readIcon, ROOT, roundPath, SOURCE, splitPath } from "./game-icons.ts";

export const CHEST_SHAPES_PATH = join(ROOT, "src/components/elements/chest-art-shapes.ts");

/** The chests' Font Awesome shapes (solid), by name. */
export const CHEST_SHAPE_NAMES = ["treasure-chest"] as const;

export function buildChestShapes(source: string = readFileSync(SOURCE, "utf8")): string {
  const lines = CHEST_SHAPE_NAMES.map((name) => {
    const { width, height, path } = readIcon(source, name);
    if (height !== 512) throw new Error(`${name}: height ${height}, the chests assume 512`);
    const parts = splitPath(path).map((p) => JSON.stringify(roundPath(p)));
    return `  ${JSON.stringify(name)}: { width: ${width}, parts: [${parts.join(", ")}] },`;
  });
  return [
    "// Generated by scripts/chest-art.ts from Font Awesome Pro 6.6.0 (solid), under the owner's Font Awesome Commercial License",
    "// (public/THIRD_PARTY_NOTICES.txt). Do not edit: run `bun run chest-art` in packages/app.",
    "",
    "/** Each chest shape's width (its height is 512) and its subpaths, each from an absolute `M`. */",
    "export const CHEST_SHAPES = {",
    ...lines,
    "} as const satisfies Record<string, { width: number; parts: readonly string[] }>;",
    "",
    "export type ChestShapeName = keyof typeof CHEST_SHAPES;",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = buildChestShapes();
  if (process.argv.includes("--check")) {
    if (readFileSync(CHEST_SHAPES_PATH, "utf8") !== text) {
      console.error("chest-art-shapes.ts is stale: run `bun run chest-art` in packages/app and commit it.");
      process.exit(1);
    }
  } else {
    writeFileSync(CHEST_SHAPES_PATH, text);
    console.log(`wrote ${CHEST_SHAPES_PATH} (${Buffer.byteLength(text)} bytes, ${CHEST_SHAPE_NAMES.length} shapes)`);
  }
}
