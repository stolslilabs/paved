/**
 * The league crests' shapes (#854): `src/components/elements/league-crest-shapes.ts` is generated from the owner's Font Awesome Pro
 * file (`vendor/fontawesome/solid.min.js`), one entry per shape a crest composes (the staff, the wheat, the bow, the helm...), cut
 * and rounded as the game icons' (`scripts/game-icons.ts`). The shapes the game icons already carry (`swords`) are not repeated:
 * `CrestArt` reads them from `game-icon-shapes.ts`.
 *
 *   node scripts/league-crests.ts            write the shapes file
 *   node scripts/league-crests.ts --check    fail when the committed file differs from what the source gives
 *
 * Node 24 runs it as is (type stripping): the syntax stays erasable. No package.
 * The drawing is Font Awesome's, unchanged; `public/THIRD_PARTY_NOTICES.txt` records each shape as derived.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { readIcon, ROOT, roundPath, SOURCE, splitPath } from "./game-icons.ts";

export const CREST_SHAPES_PATH = join(ROOT, "src/components/elements/league-crest-shapes.ts");

/** The crests' Font Awesome shapes (solid), by name: #854's motifs, Wood to Grand Master. */
export const CREST_SHAPE_NAMES = ["bow-arrow", "crown", "flag-swallowtail", "helmet-battle", "sack", "shield", "staff", "sword", "wheat"] as const;

export function buildCrestShapes(source: string = readFileSync(SOURCE, "utf8")): string {
  const lines = CREST_SHAPE_NAMES.map((name) => {
    const { width, height, path } = readIcon(source, name);
    if (height !== 512) throw new Error(`${name}: height ${height}, the crests assume 512`);
    const parts = splitPath(path).map((p) => JSON.stringify(roundPath(p)));
    return `  ${JSON.stringify(name)}: { width: ${width}, parts: [${parts.join(", ")}] },`;
  });
  return [
    "// Generated by scripts/league-crests.ts from Font Awesome Pro 6.6.0 (solid), under the owner's Font Awesome Commercial License",
    "// (public/THIRD_PARTY_NOTICES.txt). Do not edit: run `bun run league-crests` in packages/app.",
    "",
    "/** Each crest shape's width (its height is 512) and its subpaths, each from an absolute `M`. */",
    "export const CREST_SHAPES = {",
    ...lines,
    "} as const satisfies Record<string, { width: number; parts: readonly string[] }>;",
    "",
    "export type CrestShapeName = keyof typeof CREST_SHAPES;",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = buildCrestShapes();
  if (process.argv.includes("--check")) {
    if (readFileSync(CREST_SHAPES_PATH, "utf8") !== text) {
      console.error("league-crest-shapes.ts is stale: run `bun run league-crests` in packages/app and commit it.");
      process.exit(1);
    }
  } else {
    writeFileSync(CREST_SHAPES_PATH, text);
    console.log(`wrote ${CREST_SHAPES_PATH} (${Buffer.byteLength(text)} bytes, ${CREST_SHAPE_NAMES.length} shapes)`);
  }
}
