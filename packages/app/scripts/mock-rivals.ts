/**
 * V2-RULES-MOCK (#741): generates `src/data/mock/rivals.ts`, the mock's 30 rival villages of PvP v2. Rival `i` is at level
 * 1 + round(19 i / 29) (S = 8 + level slots), its crowns spread over the low leagues with its level; it is dealt S - 1 cards
 * of the base deck (a partial Fisher-Yates, the `k`-th pick `Poseidon('RIVAL', i, k)`) and lays them out with the engine's
 * search (`packages/game-core/src/rules/grow.ts`): a beam of 3 boards for two rivals in three, of 1 for the third (a casual
 * layout, which concedes more stars). Deterministic: run it again and the file is the same.
 *
 *   cd packages/app && bun scripts/mock-rivals.ts
 */
import { writeFileSync } from "node:fs";
import { poseidon } from "../../game-core/src/engine/draw";
import { growLayout } from "../../game-core/src/rules/grow";
import { BASE_DECK_CARDS, basePlanOfCard } from "../../game-core/src/rules/rarity";
import { slotsOf } from "../../game-core/src/rules/xp";

const NAMES = [
  "Rook of Ashford", "millstone_mara", "Vael", "harbourwright", "Old Tom Cobble", "Wren", "Bramblegate", "kestrel.eth", "Mossy Quill",
  "Lantern Hollow", "fenwick", "Ida of the Ford", "Tallow & Tar", "oakenshaw", "Sable Moor", "Pip Larkspur", "the_carter", "Greywater",
  "Hazel Thorne", "Ninefields", "Corwin Vale", "saltmarsh", "Odd Brannigan", "Thistledown", "Marrow Lane", "Isolde", "stonebridge_99",
  "Hob Underhill", "Quarry Queen", "Elder Ashby",
] as const;

const RIVAL = 0x524956414cn; // 'RIVAL'
const COUNT = 30;
/** The crowns of the last rival: about Bronze I (league 7, 1,400). */
const TOP_CROWNS = 1_400;

function deal(i: number, count: number): number[] {
  const deck = Array.from({ length: BASE_DECK_CARDS }, (_, card) => basePlanOfCard(card));
  for (let k = 0; k < count; k++) {
    const pick = k + Number(poseidon(RIVAL, i, k) % BigInt(deck.length - k));
    [deck[k], deck[pick]] = [deck[pick]!, deck[k]!];
  }
  return deck.slice(0, count);
}

const rows: string[] = [];
for (let i = 0; i < COUNT; i++) {
  const level = 1 + Math.round((19 * i) / (COUNT - 1));
  const slots = slotsOf(level);
  const jitter = Number(poseidon(RIVAL, i, 1_000) % 61n) - 30;
  const crowns = Math.max(0, Math.round((TOP_CROWNS * i) / (COUNT - 1)) + jitter);
  const grown = growLayout(deal(i, slots - 1), { width: i % 3 === 2 ? 1 : 3 });
  const tiles = grown.tiles.map((t) => `[${t.plan}, ${t.orientation}, ${t.x}, ${t.y}]`).join(", ");
  rows.push(`  { name: ${JSON.stringify(NAMES[i])}, level: ${level}, crowns: ${crowns}, score: ${grown.score}, tiles: [${tiles}] },`);
  console.log(`${i} ${NAMES[i]}: level ${level}, ${grown.tiles.length + 1} / ${slots} tiles, score ${grown.score}`);
}

const file = `// Generated by \`scripts/mock-rivals.ts\`; do not edit by hand.

/** A rival village of the mock (PvP v2): its name, level, crowns, layout score, and tiles as [plan, orientation, x, y], the starter left out. */
export interface RivalSeed {
  readonly name: string;
  readonly level: number;
  readonly crowns: number;
  readonly score: number;
  readonly tiles: readonly (readonly [number, number, number, number])[];
}

export const RIVAL_SEEDS: readonly RivalSeed[] = [
${rows.join("\n")}
];
`;
writeFileSync(new URL("../src/data/mock/rivals.ts", import.meta.url), file);
