// Generates `src/rules/starter-layouts.ts` (#741): the 64 starter layouts of PvP v2. Layout candidate `k` deals 8 cards from
// the base deck's common and uncommon cards (a partial Fisher-Yates, the `i`-th pick `Poseidon('STARTERS', k, i)`), then
// grows them with the engine's search (`src/rules/grow.ts`); it is kept when all 8 are placed and the layout scores more
// than 0. Deterministic: run it again and the file is the same (`__tests__/v2-rules.test.ts` checks the first layouts).
//
//   cd packages/game-core && bun scripts/v2-layouts.ts

import { writeFileSync } from "node:fs";
import { poseidon } from "../src/engine/draw";
import { growLayout } from "../src/rules/grow";
import { BASE_DECK_CARDS, basePlanOfCard, rarityOf } from "../src/rules/rarity";
import { STARTER_TILES } from "../src/rules/starters";
import type { LayoutTile } from "../src/rules/free-village";

export const STARTER_COUNT = 64;
export const STARTER_WIDTH = 24;
const DEAL = 0x5354415254455253n; // 'STARTERS'

/** The cards a starter may be dealt: the base deck's common and uncommon ones, by plan code. */
const POOL = Array.from({ length: BASE_DECK_CARDS }, (_, card) => basePlanOfCard(card)).filter((plan) => rarityOf(plan) !== "mythic");

/** The plans of candidate `k`. */
export function starterDeal(k: number): number[] {
  const pool = [...POOL];
  for (let i = 0; i < STARTER_TILES; i++) {
    const pick = i + Number(poseidon(DEAL, k, i) % BigInt(pool.length - i));
    [pool[i], pool[pick]] = [pool[pick]!, pool[i]!];
  }
  return pool.slice(0, STARTER_TILES);
}

/** Candidate `k`'s layout, or null when it is not kept. */
export function starterCandidate(k: number): { tiles: LayoutTile[]; score: number } | null {
  const grown = growLayout(starterDeal(k), { width: STARTER_WIDTH });
  return grown.unplaced.length === 0 && grown.score > 0 ? { tiles: grown.tiles, score: grown.score } : null;
}

if (import.meta.main) {
  const layouts: { k: number; tiles: LayoutTile[]; score: number }[] = [];
  for (let k = 0; layouts.length < STARTER_COUNT; k++) {
    const found = starterCandidate(k);
    if (found) layouts.push({ k, ...found });
  }
  const rows = layouts.map(
    (l) => `  // candidate ${l.k}, score ${l.score}\n  [${l.tiles.map((t) => `{ plan: ${t.plan}, orientation: ${t.orientation}, x: ${t.x}, y: ${t.y} }`).join(", ")}],`,
  );
  const file = `// Generated by \`scripts/v2-layouts.ts\`; do not edit by hand.
import type { LayoutTile } from "./free-village";

/** The starter layouts (the starter left out), in candidate order; each scores more than 0. */
export const STARTER_LAYOUTS: readonly (readonly LayoutTile[])[] = [
${rows.join("\n")}
];
`;
  writeFileSync(new URL("../src/rules/starter-layouts.ts", import.meta.url), file);
  console.log(`${layouts.length} layouts from ${layouts.at(-1)!.k + 1} candidates; scores ${Math.min(...layouts.map((l) => l.score))} to ${Math.max(...layouts.map((l) => l.score))}`);
}
